import fs from 'fs'
import path from 'path'

const root = process.cwd()
const standaloneDir = path.join(root, '.next', 'standalone')

if (fs.existsSync(standaloneDir)) {
  // 1. Copy public -> .next/standalone/public
  const publicSrc = path.join(root, 'public')
  const publicDest = path.join(standaloneDir, 'public')
  if (fs.existsSync(publicSrc)) {
    fs.cpSync(publicSrc, publicDest, { recursive: true })
    console.log('[standalone] Copied public/ -> .next/standalone/public/')
  }

  // 2. Copy .next/static -> .next/standalone/.next/static
  const staticSrc = path.join(root, '.next', 'static')
  const staticDest = path.join(standaloneDir, '.next', 'static')
  if (fs.existsSync(staticSrc)) {
    fs.cpSync(staticSrc, staticDest, { recursive: true })
    console.log('[standalone] Copied .next/static/ -> .next/standalone/.next/static/')
  }

  // 3. Copy prisma -> .next/standalone/prisma
  const prismaSrc = path.join(root, 'prisma')
  const prismaDest = path.join(standaloneDir, 'prisma')
  if (fs.existsSync(prismaSrc)) {
    fs.cpSync(prismaSrc, prismaDest, { recursive: true })
    console.log('[standalone] Copied prisma/ -> .next/standalone/prisma/')
  }

  // 4. Copy temp/paperless_invoices_v5 -> .next/standalone/temp/paperless_invoices_v5
  const sampleSrc = path.join(root, 'temp', 'paperless_invoices_v5')
  const sampleDest = path.join(standaloneDir, 'temp', 'paperless_invoices_v5')
  if (fs.existsSync(sampleSrc)) {
    fs.cpSync(sampleSrc, sampleDest, { recursive: true })
    console.log('[standalone] Copied temp/paperless_invoices_v5 -> .next/standalone/temp/paperless_invoices_v5')
  }

  // 4. Remove any 0-byte dummy SQLite databases generated by Prisma client
  const dummyDbPath = path.join(standaloneDir, 'node_modules', '.prisma', 'client', 'dev.db')
  if (fs.existsSync(dummyDbPath)) {
    try {
      const stat = fs.statSync(dummyDbPath)
      if (stat.size === 0) {
        fs.unlinkSync(dummyDbPath)
        console.log('[standalone] Cleaned 0-byte dummy dev.db in .prisma/client/')
      }
    } catch {}
  }
}
