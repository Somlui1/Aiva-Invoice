/**
 * Ingest real engine dataset from `temp/paperless_invoices_v5/` into the Portal database
 * and generate `src/mock/initialDocs.ts` so mock and database modes remain 100% in sync.
 */
import fs from 'node:fs'
import path from 'node:path'
import { runIngestSimulation } from './simulate-engine-push'
import { verifyAgainstEngineSummary, reportVerification } from './verify-against-engine-summary'
import { transformEngineResultToPortalDoc } from '../src/features/engine/adapters/engineToPortalAdapter'
import { portalDocToInvoiceDoc } from '../src/features/engine/adapters/portalDocToInvoiceDoc'

const DIR = 'temp/paperless_invoices_v5'

async function main() {
  console.log(`[seed-v5] 1. Resetting database and ingesting 125 real invoices from ${DIR}...`)
  
  // Wipe tables
  const { prisma } = await import('../src/lib/prisma')
  await prisma.validationRun.deleteMany()
  await prisma.document.deleteMany()

  // Ingest all 125 documents
  const stats = await runIngestSimulation({ dir: DIR, log: console.log })
  const verification = await verifyAgainstEngineSummary(DIR)
  const ok = reportVerification(verification, stats)

  if (!ok || stats.failed > 0) {
    console.error('[seed-v5] Ingestion failed or did not match summary.json!')
    process.exit(1)
  }

  console.log(`[seed-v5] 2. Generating src/mock/initialDocs.ts from real engine results...`)
  const absDir = path.resolve(process.cwd(), DIR)
  const files = fs.readdirSync(absDir).filter(f => f.startsWith('DMS-') && f.endsWith('_result.json'))

  // Sort files numerically by doc number
  files.sort((a, b) => {
    const numA = parseInt(a.replace(/[^0-9]/g, ''), 10)
    const numB = parseInt(b.replace(/[^0-9]/g, ''), 10)
    return numA - numB
  })

  const transformedDocs = files.map(file => {
    const raw = JSON.parse(fs.readFileSync(path.join(absDir, file), 'utf-8'))
    const portalDoc = transformEngineResultToPortalDoc(raw)
    return portalDocToInvoiceDoc(portalDoc)
  })

  const fileHeader = `// Code generated by scripts/seed-invoices-v5.ts from temp/paperless_invoices_v5. DO NOT EDIT DIRECTLY.
import { InvoiceDoc } from '../types/invoice'

export const INITIAL_DOCS: InvoiceDoc[] = `

  const fileContent = fileHeader + JSON.stringify(transformedDocs, null, 2) + '\n\nexport const initialDocs = INITIAL_DOCS\n'

  const targetPath = path.resolve(process.cwd(), 'src/mock/initialDocs.ts')
  fs.writeFileSync(targetPath, fileContent, 'utf-8')
  console.log(`[seed-v5] Successfully wrote ${transformedDocs.length} real documents to ${targetPath}`)

  await prisma.$disconnect()
  console.log('[seed-v5] Complete!')
}

main().catch(err => {
  console.error(err)
  process.exit(1)
})
