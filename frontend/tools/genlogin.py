import re,glob,sys
sys.path.insert(0,'tools')
from cssparse import *
src=''.join(open(f).read() for f in glob.glob('src/features/login/**/*.tsx',recursive=True))
cls=set()
for m in re.finditer(r'className=(?:"([^"]*)"|\{`([^`]*)`\}|\{\[([^\]]*)\])',src):
    t=' '.join(x for x in m.groups() if x)
    cls|=set(re.findall(r'[a-zA-Z][\w-]+',t))
cls|={'lg-hero','lg-theme','brand-tile','logo-mark','wordmark','wm','tg','pp2','theme-sw','lg-orb','lg-grid','d3','d3-l','d3-r','seg','spn','go'}
GENERIC={'on','sm','lg','md','t','s','b','i','a','f','x','ok','err','warn','info','block','primary','show','go','dis','sel','n','k','v','tx','ic','ico','is-busy','hint','mid'}
key={c for c in cls if c not in GENERIC}
def split_sel(s):
    out=[];d=0;cur=''
    for c in s:
        if c in '([':d+=1
        if c in ')]':d-=1
        if c==',' and d==0:out.append(cur.strip());cur='';continue
        cur+=c
    out.append(cur.strip());return [x for x in out if x]
def pre(sel):
    m=re.match(r'^(:root(?:\[[^\]]*\])?|html(?:\[[^\]]*\]|\.[\w-]+)*)\s+(.*)$',sel)
    if m:return m.group(1)+' #lg '+m.group(2)
    return '#lg '+sel
out=['/* AUTO-GENERATED by tools/genlogin.py — ยกกฎของ theme.css/fx.css ที่เกี่ยวกับหน้า Login ขึ้นใต้ #lg\n   เพื่อชนะ selector .aiva-login .xxx ของ login.css เดิม (ให้หน้าตาเหมือน aiva-react) */']
n=0
for f in ['src/styles/aiva/theme.css','src/styles/aiva/fx.css']:
    for ctx,sel,body in parse(open(f).read()):
        if body is None:continue
        ss=split_sel(sel);keep=[]
        for x in ss:
            if x.startswith('#lg') or '#splash' in x or 'cmdk' in x or '.nav' in x or '.topbar' in x:continue
            c=set(re.findall(r'\.([a-zA-Z][\w-]*)',x))
            if c & key:keep.append(pre(x))
        if not keep:continue
        r=','.join(keep)+'{'+body+'}'
        for c in reversed(ctx):r=c+'{'+r+'}'
        out.append(r);n+=1
open('src/styles/aiva/login-theme.css','w').write('\n'.join(out)+'\n')
print(n,sorted(key)[:80])
